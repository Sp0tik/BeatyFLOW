"""Фільтри хендлерів."""

from aiogram import F

from app.keyboards import MENU_TEXTS

# Фільтр для кроків текстового введення FSM («введіть ціну / тривалість / ім'я»).
#
# Без нього хендлер стану «з'їдає» будь-яке повідомлення: натиск кнопки
# постійного меню («📅 Записатися», «🧾 Послуги та ціни»…) або /команди
# сприймався як введене значення, і користувач чув «Не розпізнав ціну…».
# Такі повідомлення мають ігноруватися станом і іти до звичайних хендлерів.
TEXT_INPUT = F.text & ~F.text.in_(MENU_TEXTS) & ~F.text.startswith("/")

# Те саме, але для кроків, де приймаються й не-текстові повідомлення
# (напр. надсилання контакту з номером телефону). Команди тут теж не чіпаємо,
# щоб /start тощо працювали навіть «всередині» стану.
NOT_MENU_TEXT = ~F.text.in_(MENU_TEXTS) & ~F.text.startswith("/")